// PUT THE SHADER AND THE PACKER INTO THE APP, FROM THE ONE PLACE THEY ARE WRITTEN.
//
// tools/lib/glass-gpu.mjs holds the WGSL and tools/lib/glass-real.mjs holds the packer that turns a
// real F into the two buffers it reads. Five probe pages import them as modules; the app is a
// single HTML file and cannot. So the app gets a copy, and a copy is a thing that drifts - which
// here would be invisible, because the probes would go on verifying the module while the exporter
// rendered from something else.
//
// This writes the copy, and tools/check-gpu-sync.mjs fails the build when the two disagree. The
// modules stay the source: edit them, run this, commit both.
//
//   node tools/sync-gpu.mjs            write the app's copy
//   node tools/check-gpu-sync.mjs      fail if it has drifted
import { readFileSync, writeFileSync } from 'fs';
import { fileURLToPath } from 'url';
import { dirname, join } from 'path';

const HERE = dirname(fileURLToPath(import.meta.url));
const ROOT = join(HERE, '..');
const APP = join(ROOT, 'app', 'stone-author.html');
const NL = String.fromCharCode(10);

export const OPEN = '  // <<<GPU-SYNC: generated by tools/sync-gpu.mjs - edit tools/lib/, not here';
export const CLOSE = '  // GPU-SYNC>>>';

// The module text, with its module plumbing taken off. Both files are written to be read, so the
// comments travel: the app is where somebody debugging an export will be looking.
function strip(path, drop) {
  let s = readFileSync(join(ROOT, 'tools', 'lib', path), 'utf8').split(chr13NL).join(NL);
  for (const re of drop) s = s.replace(re, '');
  // AN IMPORT CAN SPAN LINES, and wood-gpu.mjs's does. The negated class crosses newlines on its
  // own, so this takes the whole statement up to its semicolon rather than one line of it - a
  // half-removed import is a syntax error in the app, which is the one failure mode that at least
  // announces itself.
  s = s.replace(/^import [^;]*;/gm, '');
  s = s.replace(/^export [{][^}]*[}];?[ ]*$/gm, '');
  s = s.replace(/^export (?=(?:const|let|var|function|async|class) )/gm, '');
  // ANY remaining `export` keyword, not a list of the ones that exist today. glass-gpu.mjs carries
  // an `export const NLC` nothing uses, which was not on the list and is a syntax error inside the
  // app - the next one added would be too. A bare `export { x };` line goes entirely; an
  // `export const`/`function`/`let` keeps its declaration and loses the keyword.
  return s.trim();
}
const chr13NL = String.fromCharCode(13) + NL;

export function generate() {
  // glass-gpu.mjs is one object of WGSL strings; it needs no plumbing but its export line.
  const wgsl = strip('glass-gpu.mjs', [/^const WGSL = \{\};\s*$/m]);
  // glass-real.mjs exports a function and a constant and declares its own NL.
  const real = strip('glass-real.mjs', [/^const NL = String\.fromCharCode\(10\);\s*$/m]);
  // WOOD'S TWO, WHICH GO IN A SCOPE OF THEIR OWN. Both materials call their arena parts PART_NAMES
  // and both declare an f32 coercion, so at the top level the second one is a redeclaration and the
  // whole app stops parsing. A block is the cheapest fix and it is also the honest one: these are
  // two materials, not one namespace, and nothing of wood's is meant to be visible to glass.
  const woodReal = strip('wood-real.mjs', []);
  const woodGpu = strip('wood-gpu.mjs', [/^const WGSL = \{\};\s*$/m]);
  // AND STONE'S TWO, in a block of their own for the same reason wood's are: all three materials
  // call their arena parts PART_NAMES, so at the top level the third is a redeclaration and the app
  // stops parsing.
  const stoneReal = strip('stone-real.mjs', []);
  const stoneGpu = strip('stone-gpu.mjs', [/^const WGSL = \{\};\s*$/m]);

  const body = [
    OPEN,
    '  //',
    '  // THE SHADER, and the packer that fills its two buffers. Verified against the CPU path',
    '  // function by function in tools/gpu-port-harness.html, whole-tile in tools/gpu-tile-probe.html,',
    '  // and for throughput in tools/gpu-sheet-probe.html. Do not edit this block: it is written from',
    '  // tools/lib/glass-gpu.mjs and tools/lib/glass-real.mjs, and check-gpu-sync fails if it drifts.',
    '  const WGSL = {};',
    indent(wgsl),
    '',
    indent(real),
    '',
    '  // ---- AND WOOD, the second material through the same path. Its shader is assembled rather',
    '  // than concatenated: woodSource closes over the calls and borrows woodAtan2, woodHash, fbm2',
    '  // and what those call in turn from the glass blocks above, so the three functions both',
    '  // materials use have one definition and one set of probes behind them.',
    '  //',
    '  // IN A BLOCK, because both materials name their arena parts PART_NAMES. Four values come out',
    '  // of it and the pool uses only those.',
    '  let WOOD_SRC = null, WOOD_PACK = null, WOOD_UNI_OFF = null, WOOD_UNI_BYTES = 0;',
    '  // CAPTURED OUT HERE, AND THAT IS NOT A STYLE CHOICE. wood-gpu.mjs declares a WGSL of its own',
    '  // and it keeps it, so inside the block that name is the WOOD one - which makes a capture in',
    '  // there a read of a const in its own temporal dead zone. The app threw on load and started',
    '  // nothing: gates green, the shader compiling on a real device, and no studio.',
    '  const GLASS_WGSL = WGSL;',
    '  {',
    indent2(woodReal),
    '',
    indent2(woodGpu),
    '',
    '    // LAZY, because assembling it measures 1.24 ms and most loads never export wood at',
    '    // all. gpuModule calls it once and memoises the compiled module.',
    '    WOOD_SRC = () => woodSource(GLASS_WGSL).code;',
    '    WOOD_PACK = packWood;',
    '    WOOD_UNI_OFF = uniOffset;',
    '    WOOD_UNI_BYTES = UNI_BYTES;',
    '  }',
    '',
    '  // ---- AND STONE, the third. Its shader owns what paintStoneContent owns and no more: the',
    '  // base modulators, then every content layer in authored order. renderOneTile still lays the',
    '  // ground and still applies the coat, which is the only reason ONE dispatch is enough - the',
    '  // coat is twelve box-blur passes and a per-pixel shader cannot do those in one.',
    '  //',
    '  // IN ITS OWN BLOCK, like wood\'s, because all three name their arena parts PART_NAMES. Four',
    '  // values come out and the pool uses only those.',
    '  let STONE_SRC = null, STONE_PACK = null, STONE_UNI_OFF = null, STONE_UNI_BYTES = 0;',
    '  // AND THE FILTER COLLAPSE, which stoneScene needs on ITS side of the line. The filter on a',
    '  // stroke acts on a colour that is constant across the whole stroke, so the matrix is applied',
    '  // once when the chunk is built and the shader never sees it. The source under a fog blob is',
    '  // col * g and varies with the gradient, so a PLANE carries its matrix into the arena instead.',
    '  let STONE_COLLAPSE = null;',
    '  {',
    indent2(stoneReal),
    '',
    indent2(stoneGpu),
    '',
    '    // LAZY for the same reason wood\'s is: most loads never export stone on the GPU at all,',
    '    // and gpuModule memoises the compiled module after the first call.',
    '    STONE_SRC = () => stoneSource(GLASS_WGSL).code;',
    '    STONE_PACK = packStone;',
    '    STONE_UNI_OFF = uniOffset;',
    '    STONE_UNI_BYTES = UNI_BYTES;',
    '    STONE_COLLAPSE = collapseFilter;',
    '  }',
    CLOSE,
  ].join(NL);
  return body;
}

// FOUR SPACES, for what sits inside the wood block. Same template-literal rule: a space inside a
// backtick is shader source and must not be touched.
function indent2(s) {
  const out = [];
  let inTpl = false;
  for (const line of s.split(NL)) {
    out.push(inTpl ? line : (line.length ? '    ' + line : line));
    const ticks = (line.match(/`/g) || []).length;
    if (ticks % 2 === 1) inTpl = !inTpl;
  }
  return out.join(NL);
}

function indent(s) {
  // two spaces, matching the app's function bodies - but never inside a template literal, where a
  // space is shader source rather than layout
  const out = [];
  let inTpl = false;
  for (const line of s.split(NL)) {
    out.push(inTpl ? line : (line.length ? '  ' + line : line));
    const ticks = (line.match(/`/g) || []).length;
    if (ticks % 2 === 1) inTpl = !inTpl;
  }
  return out.join(NL);
}

export function splice(appSrc, body) {
  const a = appSrc.indexOf(OPEN);
  const b = appSrc.indexOf(CLOSE);
  if (a < 0 || b < 0) {
    throw new Error('the app has no GPU-SYNC markers - add them around the generated block first');
  }
  if (b < a) throw new Error('the GPU-SYNC markers are the wrong way round in the app');
  return appSrc.slice(0, a) + body + appSrc.slice(b + CLOSE.length);
}

export function currentBlock(appSrc) {
  const a = appSrc.indexOf(OPEN);
  const b = appSrc.indexOf(CLOSE);
  if (a < 0 || b < 0) return null;
  return appSrc.slice(a, b + CLOSE.length);
}

if (process.argv[1] && process.argv[1].endsWith('sync-gpu.mjs')) {
  const raw = readFileSync(APP, 'utf8');
  const crlf = raw.includes(chr13NL);
  const src = raw.split(chr13NL).join(NL);
  const body = generate();
  const out = splice(src, body);
  if (out === src) { console.log('sync-gpu: already in sync'); process.exit(0); }
  writeFileSync(APP, crlf ? out.split(NL).join(chr13NL) : out);
  console.log('sync-gpu: wrote ' + body.split(NL).length + ' lines into app/stone-author.html');
}
