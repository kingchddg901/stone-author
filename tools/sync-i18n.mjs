// THE APP CARRIES EVERY LOCALE INSIDE IT. This generates that block from i18n/.
//
// English was always inlined — it is the source of truth and check-i18n reads it straight out of the
// HTML. The other fifteen were fetched at runtime from i18n/<lang>.json, which meant the "one file"
// the app claims to be was one file IN ENGLISH ONLY: open it from disk and `fetch` is blocked
// outright, the catch swallows the failure, and setLang falls back to 'en' without a word. A reader
// who downloaded the studio got a monolingual one and no way to tell why.
//
// So the packs are inlined, and i18n/ stays the editable source. That is the same arrangement as the
// shader (see sync-gpu.mjs / check-gpu-sync.mjs): a copy in the app, a file on disk, and a gate that
// refuses to let them differ. Without the gate an inline copy is strictly worse than a fetch, because
// a translator's edit would land in the file, pass check-i18n — which reads the FILE for the packs —
// and never reach a reader.
//
// ONE LANGUAGE PER LINE, deliberately. The whole block as a single literal would be a million-byte
// line, and every pack edit would show as one changed line of one million characters. Per-language
// lines mean a diff says "de and ja changed".
//
// JSON.parse RATHER THAN AN OBJECT LITERAL. It is faster for data this size, and it sidesteps every
// JS-escaping question in fifteen languages at once: the only escaping that matters is the one the
// JSON string itself needs, which JSON.stringify already does correctly.
//
//   node tools/sync-i18n.mjs        regenerate the block in the app
//   node tools/sync-i18n.mjs --check  print what would change, write nothing
import { readFileSync, writeFileSync, readdirSync } from 'fs';
import { fileURLToPath } from 'url';
import { dirname, join } from 'path';

const HERE = dirname(fileURLToPath(import.meta.url));
const ROOT = join(HERE, '..');
const APP = join(ROOT, 'app', 'stone-author.html');
const I18N = join(ROOT, 'i18n');
const NL = String.fromCharCode(10);
const CRLF = String.fromCharCode(13) + NL;

export const OPEN = '  // <<<I18N-SYNC: generated by tools/sync-i18n.mjs - edit i18n/, not here';
export const CLOSE = '  // I18N-SYNC>>>';

// `</` ENDS A SCRIPT BLOCK WHEREVER IT APPEARS, including inside a string literal — the HTML parser
// does not know it is in one. The packs are full of markup (`<b>Granite.</b>` and friends), so one
// unescaped `</` would truncate the app at that byte. `<\/` is the same string to JavaScript and
// invisible to the parser, which is why every serialiser that writes JS into HTML does this.
const jsString = obj => JSON.stringify(JSON.stringify(obj)).split('</').join('<\\/');

export function langs() {
  return readdirSync(I18N)
    .filter(f => f.endsWith('.json') && !f.startsWith('_'))
    .map(f => f.slice(0, -5))
    .sort();
}

export function generate() {
  const index = JSON.parse(readFileSync(join(I18N, '_index.json'), 'utf8'));
  const out = [
    OPEN,
    '  //',
    '  // Fifteen packs and the catalogue, lifted from i18n/ by tools/sync-i18n.mjs and held identical',
    '  // to it by tools/check-i18n-sync.mjs. EDIT THE FILES, NOT THIS: an edit here is overwritten by',
    '  // the next sync, and an edit to the files that is not synced fails the gate rather than',
    '  // shipping a pack no reader can reach.',
    '  //',
    '  // The catalogue carries each language’s own word for "draft", so the menu can say',
    '  // "Deutsch (Entwurf)" and the draft gate can refuse to IMPOSE an unreviewed pack on a browser',
    '  // that merely happens to be set to it. Inlining changes none of that — it only means the',
    '  // catalogue is known before the first frame instead of one fetch later.',
    '  Object.assign(INDEX, JSON.parse(' + jsString(index) + '));',
    '  Object.assign(PACKS, {',
  ];
  for (const l of langs()) {
    const pack = JSON.parse(readFileSync(join(I18N, l + '.json'), 'utf8'));
    out.push('    ' + JSON.stringify(l) + ': JSON.parse(' + jsString(pack) + '),');
  }
  out.push('  });');
  out.push(CLOSE);
  return out.join(NL);
}

export function splice(appSrc, body) {
  const a = appSrc.indexOf(OPEN);
  const b = appSrc.indexOf(CLOSE);
  if (a < 0 || b < 0) throw new Error('the app has no I18N-SYNC markers - add them around the generated block first');
  if (b < a) throw new Error('the I18N-SYNC markers are the wrong way round in the app');
  return appSrc.slice(0, a) + body + appSrc.slice(b + CLOSE.length);
}

export function currentBlock(appSrc) {
  const a = appSrc.indexOf(OPEN);
  const b = appSrc.indexOf(CLOSE);
  if (a < 0 || b < 0) return null;
  return appSrc.slice(a, b + CLOSE.length);
}

if (process.argv[1] && process.argv[1].endsWith('sync-i18n.mjs')) {
  const raw = readFileSync(APP, 'utf8');
  const crlf = raw.includes(CRLF);
  const src = raw.split(CRLF).join(NL);
  const body = generate();
  const have = currentBlock(src);
  const ls = langs();
  if (process.argv.includes('--check')) {
    console.log(have === body ? 'i18n-sync: the block is current' : 'i18n-sync: the block would change');
    process.exit(have === body ? 0 : 1);
  }
  const out = splice(src, body);
  writeFileSync(APP, crlf ? out.split(NL).join(CRLF) : out);
  const kb = n => (n / 1024).toFixed(0) + ' KB';
  console.log('i18n-sync: inlined ' + ls.length + ' pack(s) - ' + ls.join(', '));
  console.log('  block ' + kb(body.length) + ', app ' + kb(raw.length) + ' -> ' + kb(out.length));
}
